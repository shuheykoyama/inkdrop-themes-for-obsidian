# The regex Inkdrop's Markdown uses for bare URLs (`Lee=/^((?:(?:aaas?|...` in 6.3.0's bundle): a list of URL schemes,
# Inkdrop's own among them. Taken as data from the installed app, not rewritten.
import sys
s = open(sys.argv[1], encoding="utf8", errors="ignore").read()
b = s.find("Lee=/^((?:")
e = s.find(",Ree=[{defineNodes", b)
if b < 0 or e < 0:
    sys.exit("regex not found: search the bundle for 'InlineURL' and adjust")
print("// Generated by tools/extract-url-regex.py from Inkdrop's renderer bundle.")
print("export const URL_RE = " + s[b + len("Lee="):e] + ";")
