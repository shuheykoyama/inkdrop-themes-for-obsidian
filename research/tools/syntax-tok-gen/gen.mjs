// Ports the token rules of Inkdrop's base stylesheet (`.cm-editor, .mde-preview .codeblock { .tok-* { color: var(--syntax-*) } ... }`
// in @inkdropapp/css syntax.css, MIT, bundled in the installed Inkdrop's app.asar) to this theme, for the token classes the
// Inkdrop highlight plugin (research/poc/inkdrop-highlight) puts into Obsidian's code (research/14 section 6.202):
//  - nesting is resolved; the scope `.cm-editor` becomes the editor's content and `.mde-preview .codeblock` Reading view's code,
//  - --syntax-* and --md-* variables become the palette's --ink-syntax-* and --ink-md-* (same values, per theme).
// usage: node gen.mjs <@inkdropapp/css/syntax.css>   writes src/common/components/syntax-tok.css
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import postcss from "postcss";
const REPO = path.resolve(import.meta.dirname, "..", "..", "..");
const root = postcss.parse(readFileSync(process.argv[2], "utf8"));
const EDITOR = ".theme-dark .markdown-source-view.mod-cm6 .cm-content";
const READING = ".theme-dark .markdown-rendered pre";
// find the one rule whose selector list is `.cm-editor, .mde-preview .codeblock`
let scopeRule = null;
root.walkRules((r) => { if (r.selectors?.join(",") === ".cm-editor,.mde-preview .codeblock") scopeRule = r; });
if (!scopeRule) throw new Error("scope rule not found");
const out = [];
const flatten = (rule, parents) => {
  const own = rule.nodes.filter((n) => n.type === "decl");
  const sels = parents.flatMap((p) => rule.selectors.map((s) => (s.includes("&") ? s.replace(/&/g, p) : p ? `${p} ${s}` : s)));
  if (own.length && parents.length) out.push({ sels, decls: own.map((d) => [d.prop, d.value]) });
  for (const n of rule.nodes) if (n.type === "rule") flatten(n, parents.length ? sels : [""].flatMap(() => n.selectors.length ? [] : []).concat(parents));
};
// the top rule has no declarations of its own: start from its children with an empty parent
for (const n of scopeRule.nodes) if (n.type === "rule") { const walk = (rule, parents) => {
  const sels = parents.flatMap((p) => rule.selectors.map((s) => (s.includes("&") ? s.replace(/&/g, p) : p ? `${p} ${s}` : s)));
  const own = rule.nodes.filter((x) => x.type === "decl");
  if (own.length) out.push({ sels, decls: own.map((d) => [d.prop, d.value.replace(/\s+/g, " ").trim()]) });
  for (const c of rule.nodes) if (c.type === "rule") walk(c, sels);
}; walk(n, [""]); }
const rename = (v) => v.replace(/var\(\s*--(syntax|md)-/g, "var(--ink-$1-").replace(/\(\s+/g, "(").replace(/\s+\)/g, ")");
// rules for classes the plugin's output never has: Inkdrop adds md-task-*, md-inline-mark and the list nesting classes with its own
// widgets and decorations, not with the Lezer token highlighter the plugin mirrors; they carry the colour literals its fallbacks hold
const NOT_PRODUCED = /md-task|md-inline-mark|md-list-mark-[23]|\.md-table/;
const quote = (s) => s.replace(/'/g, '"');
const lines = [`/* Component: Inkdrop's token colours for the classes the Inkdrop highlight plugin puts into code (research/14 §6.202).`,
  `   Generated by research/tools/syntax-tok-gen/gen.mjs from @inkdropapp/css syntax.css (the \`.cm-editor, .mde-preview .codeblock\``,
  `   rules), not edited by hand. The classes exist only where the plugin runs: the Source mode / Live Preview editor content (also`,
  `   front matter and $$ blocks) and the code of Reading view; without the plugin no element matches. */`,
  `/* The two scopes (editor, Reading view) never match the same element, and the rules keep Inkdrop's order, which the official lint's`,
  `   specificity-order rule does not know. */`, `/* stylelint-disable no-descending-specificity */`, ""];
const used = new Set();
for (const r of out) {
  if (r.sels.some((x) => NOT_PRODUCED.test(x))) continue;
  const rel = r.sels.map(quote).map((s) => s.replace(/^\s+/, ""));
  const selector = rel.flatMap((s) => [`${EDITOR} ${s}`, `${READING} ${s}`]).join(",\n");
  lines.push(`${selector} {`);
  for (const [p, v] of r.decls) { const nv = rename(v); for (const m of nv.matchAll(/var\((--ink-[\w-]+)/g)) used.add(m[1]); lines.push(`  ${p}: ${nv};`); }
  lines.push("}", "");
}
lines.push("/* stylelint-enable no-descending-specificity */", "");
writeFileSync(path.join(REPO, "src/common/components/syntax-tok.css"), lines.join("\n"));
// every palette variable the rules read must exist in both themes (Inkdrop leaves a few undefined on purpose: reported, not failed)
const missing = {};
for (const t of ["solarized-dark", "kanagawa-dragon"]) {
  const pal = readFileSync(path.join(REPO, "src/palette", `${t}.css`), "utf8");
  missing[t] = [...used].filter((v) => !pal.includes(`${v}:`));
}
console.log(`${out.length} rules; variables used ${used.size}; undefined in the palette: SD ${missing["solarized-dark"].length}, KD ${missing["kanagawa-dragon"].length}`);
console.log("SD:", missing["solarized-dark"].join(" ")); console.log("KD:", missing["kanagawa-dragon"].join(" "));
