// Build: Vanilla CSS + PostCSS (Q-D21). The only plugin is postcss-import, which inlines the @import
// rules of each theme entry (src/themes/<theme>.css). No colour conversion, no minification, no nesting
// expansion. Reused from the Q-D21 PoC (research/poc/q-d21-build/p1-postcss/build.mjs, research/13).
//
// Output per theme: dist/<theme>/theme.css and dist/<theme>/manifest.json (development manifest from
// src/manifests; the name is a placeholder, Q-D18 is undecided).
//
// usage: node scripts/build.mjs [--src <dir>] [--out <dir>]
// Exit status is non-zero if any theme fails (missing source, postcss warning, unreadable manifest).
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { parseArgs } from "node:util";
import postcss from "postcss";
import atImport from "postcss-import";

export const THEMES = ["solarized-dark", "kanagawa-dragon"];

const root = path.resolve(import.meta.dirname, "..");
const { values: args } = parseArgs({ options: { src: { type: "string" }, out: { type: "string" } } });
const srcDir = path.resolve(args.src ?? path.join(root, "src"));
const outDir = path.resolve(args.out ?? path.join(root, "dist"));

// Fixed header: no timestamp or path, so two builds of the same sources are byte-identical.
const header = (theme) => `/* ${theme}: generated by scripts/build.mjs from src/themes/${theme}.css. Do not edit.
   Development build. The theme name and the licence/attribution text are not final (Q-D18, Q-D19).
   Colour values are Inkdrop's declarations; the source of each one is in the palette comments. */`;

// Layout only: put one blank line between top-level nodes coming from different files, which the
// official lint config (stylelint-config-standard: rule-empty-line-before, comment-empty-line-before)
// expects. Values, selectors and order are not touched.
function separateTopLevelNodes(root) {
  root.nodes.forEach((node, i) => {
    node.raws.before = i === 0 ? "" : "\n\n";
  });
}

for (const theme of THEMES) {
  const from = path.join(srcDir, "themes", `${theme}.css`);
  const themeOut = path.join(outDir, theme);
  try {
    const result = await postcss([atImport()]).process(await readFile(from, "utf8"), { from, to: path.join(themeOut, "theme.css"), map: false });
    for (const w of result.warnings()) console.error(`warning: ${theme}: ${w.toString()}`);
    // A warning (e.g. an @import postcss-import could not inline) fails the build.
    if (result.warnings().length) throw new Error("postcss reported warnings");
    separateTopLevelNodes(result.root);
    const css = `${header(theme)}\n\n${result.root.toString().trim()}\n`;
    // The manifest is parsed so that a broken file fails here, then written with stable formatting.
    const manifest = JSON.parse(await readFile(path.join(srcDir, "manifests", `${theme}.json`), "utf8"));
    await mkdir(themeOut, { recursive: true });
    await writeFile(path.join(themeOut, "theme.css"), css);
    await writeFile(path.join(themeOut, "manifest.json"), `${JSON.stringify(manifest, null, 2)}\n`);
    console.log(`built: ${path.relative(process.cwd(), path.join(themeOut, "theme.css"))}`);
  } catch (err) {
    console.error(`build failed: ${theme}: ${err.message}`);
    process.exitCode = 1;
  }
}
